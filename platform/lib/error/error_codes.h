#ifndef NETOS_PLATFORM_LIB_ERROR_CODES_H
#define NETOS_PLATFORM_LIB_ERROR_CODES_H

namespace netos {

namespace lib {

enum netos_status {
    NETOS_STATUS_SUCCESS                            = 0x00000000,

    /* Incorrect input. */
    NETOS_STATUS_INVAL_INPUT                        = 0x00000001,
    NETOS_STATUS_INVAL_MACADDR                      = 0x00000002,
    /* malloc/ calloc failures.. */
    NETOS_STATUS_ALLOC_FAILURE                      = 0x00000003,
    /* frame is incorrect. */
    NETOS_STATUS_MALFORMED_PKT                      = 0x00000004,
    NETOS_STATUS_INVAL_HEXA_STR                     = 0x00000005,
    NETOS_STATUS_INVAL_IPV4_ADDR                    = 0x00000006,
    NETOS_STATUS_TIMERFD_CREATE_FAIL                = 0x00000007,
    NETOS_STATUS_TIMERFD_SETTIME_FAIL               = 0x00000008,
    NETOS_STATUS_INVAL_CONFIG                       = 0x00000009,

    /* Parser uses these error codes. */
    NETOS_STATUS_UNSUPPORTED_L2_PROTOCOL            = 0x00000107,
    NETOS_STATUS_UNSUPPORTED_L3_PROTOCOL            = 0x00000108,
    NETOS_STATUS_UNSUPPORTED_L4_PROTOCOL            = 0x00000109,
    NETOS_STATUS_UNSUPPORTED_ICMP_TYPE              = 0x0000010A,
    NETOS_STATUS_INVAL_ICMP_CHECKSUM                = 0x0000010B,
    NETOS_STATUS_UNSUPPORTED_IEEE8021X_TYPE         = 0x0000010C,
    NETOS_STATUS_UNSUPPORTED_ICMPV6_TYPE            = 0x0000010D,

    /* Cryptography related error codes. */
    NETOS_STATUS_CRYPTO_PKEY_CTX_ERROR              = 0x00001001,
    NETOS_STATUS_CRYPTO_PKEY_GEN_ERROR              = 0x00001002,
    NETOS_STATUS_CRYPTO_INVAL_RSA_KEY_LEN           = 0x00001003,
    NETOS_STATUS_CRYPTO_INVAL_DIGEST                = 0x00001004,
    NETOS_STATUS_CRYPTO_GCM_AAD_LEN_INVAL           = 0x00001005,
    NETOS_STATUS_CRYPTO_GCM_INVAL_INPUT             = 0x00001006,
    NETOS_STATUS_CRYPTO_WOLFSSL_GCM_INIT_FAILED     = 0x00001007,
    NETOS_STATUS_CRYPTO_WOLFSSL_GCM_SET_KEY_FAILED  = 0x00001008,
    NETOS_STATUS_CRYPTO_WOLFSSL_GCM_ENCRYPT_FAILED  = 0x00001009,
    NETOS_STATUS_CRYPTO_WOLFSSL_GCM_DECRYPT_FAILED  = 0x0000100A,
    NETOS_STATUS_CRYPTO_WOLFSSL_GMAC_INIT_FAILED    = 0x0000100B,
    NETOS_STATUS_CRYPTO_WOLFSSL_GMAC_SET_KEY_FAILED = 0x0000100C,
    NETOS_STATUS_CRYPTO_WOLFSSL_GMAC_GEN_TAG_FAILED = 0x0000100D,
    NETOS_STATUS_CRYPTO_WOLFSSL_GMAC_VER_TAG_FAILED = 0x0000100E,

    NETOS_STATUS_MACSEC_SECY_NOT_FOUND              = 0x00002001,
    NETOS_STATUS_MACSEC_AN_INVAL                    = 0x00002002,

    NETOS_STATUS_GENERIC_ERROR                      = 0xFEFEFEFE,
};

}

}

#endif
